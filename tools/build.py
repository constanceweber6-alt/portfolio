"""Builds index.html and assets/i18n.js from src/index.template.html and content/*.json.

English text is written into the HTML (for search engines and link previews);
French and Japanese are swapped in by assets/main.js.

Usage: python3 tools/build.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE_URL = "https://constanceweber6-alt.github.io/portfolio/"
CONFIG = json.loads((ROOT / "content" / "config.json").read_text(encoding="utf-8"))
LANGS = ["en", "fr", "ja"]

content = {lang: json.loads((ROOT / "content" / f"{lang}.json").read_text(encoding="utf-8")) for lang in LANGS}

# Every language must have the same keys
keys = set(content["en"])
for lang in LANGS[1:]:
    missing, extra = keys - set(content[lang]), set(content[lang]) - keys
    assert not missing and not extra, f"{lang}: missing {missing}, extra {extra}"

# No long dashes anywhere in the copy
for lang in LANGS:
    for k, v in content[lang].items():
        assert "—" not in v and "–" not in v, f"long dash in {lang}.{k}"

tpl = (ROOT / "src" / "index.template.html").read_text(encoding="utf-8")
en = content["en"]


def fill(match):
    key = match.group(2)
    assert key in en, f"unknown key {key}"
    return f'{match.group(1)}data-k="{key}"{match.group(3)}>{html.escape(en[key], quote=False)}</'


out = re.sub(r'(<[a-z0-9]+[^>]*?)data-k="([a-z0-9_]+)"([^>]*)></', fill, tpl)
out = out.replace("{{SITE_URL}}", SITE_URL).replace("{{EMAIL}}", CONFIG["email"])
out = re.sub(r"\{\{([a-z0-9_]+)\}\}", lambda m: html.escape(en[m.group(1)]), out)
assert "{{" not in out, "unfilled placeholder"
(ROOT / "index.html").write_text(out, encoding="utf-8")

cv = {
    "available": all((ROOT / p).exists() for p in CONFIG["cv"].values()),
    "en": CONFIG["cv"]["en"],
    "fr": CONFIG["cv"]["fr"],
}
data = dict(content)
data["cv"] = cv
(ROOT / "assets" / "i18n.js").write_text(
    "/* Generated by tools/build.py from content/*.json. Do not edit by hand. */\nwindow.I18N = "
    + json.dumps(data, ensure_ascii=False, indent=1)
    + ";\n",
    encoding="utf-8",
)
# Cache busting: each asset link gets a short hash of its content
import hashlib
page = (ROOT / "index.html").read_text(encoding="utf-8")
for asset in ["assets/style.css", "assets/i18n.js", "assets/main.js"]:
    h = hashlib.sha1((ROOT / asset).read_bytes()).hexdigest()[:8]
    page = page.replace(f'"{asset}"', f'"{asset}?v={h}"')
(ROOT / "index.html").write_text(page, encoding="utf-8")

print("built index.html and assets/i18n.js", "(CV files found)" if cv["available"] else "(CV files missing: buttons hidden)")
